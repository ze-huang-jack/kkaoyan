def set_cell_font(cell, text, font_name='宋体', font_size=10.5, bold=False):
    """设置单元格字体（清除旧段落再写）"""
    for p in cell.paragraphs:
        for r in p.runs:
            r.clear()
    p = cell.paragraphs[0]
    p.clear()
    run = p.add_run(str(text))
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = Pt(font_size)
    run.bold = bold
    return p

def add_paragraph(doc, text, font_name='宋体', font_size=12, bold=False,
                  alignment=None, space_after=6, first_line_indent=None):
    """添加格式化段落"""
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = Pt(font_size)
    run.bold = bold
    p.paragraph_format.space_after = Pt(space_after)
    if alignment is not None:
        p.alignment = alignment
    if first_line_indent:
        p.paragraph_format.first_line_indent = Pt(first_line_indent)
    return p

def add_heading_styled(doc, text, level=1):
    """添加标题（黑体）"""
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.name = '黑体'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')
    return h

def set_default_font(doc):
    """设置文档默认字体"""
    style = doc.styles['Normal']
    font = style.font
    font.name = '宋体'
    font.size = Pt(12)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')


